"""Tests for the User and Resume models against real PostgreSQL."""

import uuid
from datetime import datetime

import pytest
from psycopg import errors as pg_errors
from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.models import Resume, User


def make_user(email: str = "student@example.com") -> User:
    return User(email=email, password_hash="not-a-real-hash")


def make_resume(user: User, **overrides) -> Resume:
    values = {
        "file_name": "My Resume.pdf",
        "file_path": f"resumes/{uuid.uuid4()}.pdf",
        "file_type": "application/pdf",
        "file_size": 52_431,
    }
    values.update(overrides)
    return Resume(user=user, **values)


def test_create_user(db_session: Session) -> None:
    user = make_user()
    db_session.add(user)
    db_session.commit()

    saved = db_session.scalars(select(User).where(User.email == "student@example.com")).one()
    assert isinstance(saved.id, uuid.UUID)
    assert saved.password_hash == "not-a-real-hash"
    # Timestamps are generated by the database and are timezone-aware.
    assert isinstance(saved.created_at, datetime)
    assert saved.created_at.tzinfo is not None
    assert saved.updated_at.tzinfo is not None


def test_user_ids_are_unique_uuids(db_session: Session) -> None:
    a, b = make_user("a@example.com"), make_user("b@example.com")
    db_session.add_all([a, b])
    db_session.commit()

    assert a.id != b.id
    assert a.id.version == 4


def test_create_resume_for_user(db_session: Session) -> None:
    user = make_user()
    resume = make_resume(user)
    db_session.add(resume)  # the user is saved too, via the relationship
    db_session.commit()

    assert isinstance(resume.id, uuid.UUID)
    assert resume.user_id == user.id
    assert resume.file_size == 52_431
    assert resume.created_at.tzinfo is not None


def test_user_resume_relationship_both_directions(db_session: Session) -> None:
    user = make_user()
    first, second = make_resume(user), make_resume(user, file_name="v2.docx")
    db_session.add(user)
    db_session.commit()

    # Forget the in-memory objects so the relationships are loaded from the DB.
    db_session.expire_all()

    loaded_user = db_session.scalars(select(User)).one()
    assert {r.id for r in loaded_user.resumes} == {first.id, second.id}

    loaded_resume = db_session.get(Resume, first.id)
    assert loaded_resume is not None
    assert loaded_resume.user.id == loaded_user.id


def test_duplicate_filenames_are_allowed(db_session: Session) -> None:
    user = make_user()
    db_session.add_all([make_resume(user, file_name="resume.pdf"),
                        make_resume(user, file_name="resume.pdf")])
    db_session.commit()

    assert len(user.resumes) == 2


def test_email_must_be_unique(db_session: Session) -> None:
    db_session.add(make_user("dup@example.com"))
    db_session.commit()

    db_session.add(make_user("dup@example.com"))
    with pytest.raises(IntegrityError) as exc_info:
        db_session.commit()
    db_session.rollback()

    assert isinstance(exc_info.value.orig, pg_errors.UniqueViolation)


def test_resume_requires_existing_user(db_session: Session) -> None:
    orphan = Resume(
        user_id=uuid.uuid4(),  # no such user
        file_name="cv.pdf",
        file_path="resumes/orphan.pdf",
        file_type="application/pdf",
        file_size=100,
    )
    db_session.add(orphan)
    with pytest.raises(IntegrityError) as exc_info:
        db_session.commit()
    db_session.rollback()

    assert isinstance(exc_info.value.orig, pg_errors.ForeignKeyViolation)


def test_resume_requires_user_id(db_session: Session) -> None:
    db_session.add(
        Resume(
            file_name="cv.pdf",
            file_path="resumes/no-user.pdf",
            file_type="application/pdf",
            file_size=100,
        )
    )
    with pytest.raises(IntegrityError) as exc_info:
        db_session.commit()
    db_session.rollback()

    assert isinstance(exc_info.value.orig, pg_errors.NotNullViolation)


def test_file_size_cannot_be_negative(db_session: Session) -> None:
    db_session.add(make_resume(make_user(), file_size=-1))
    with pytest.raises(IntegrityError) as exc_info:
        db_session.commit()
    db_session.rollback()

    assert isinstance(exc_info.value.orig, pg_errors.CheckViolation)


def test_deleting_user_deletes_their_resumes(db_session: Session) -> None:
    user = make_user()
    resume = make_resume(user)
    db_session.add(user)
    db_session.commit()
    resume_id = resume.id

    db_session.delete(user)
    db_session.commit()
    db_session.expire_all()

    assert db_session.get(Resume, resume_id) is None
